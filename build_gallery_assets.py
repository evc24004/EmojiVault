from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
import json
import math
from pathlib import Path
from typing import Any
from PIL import Image, ImageOps

GRID_DIM = 16
ITEMS_PER_SHEET = GRID_DIM * GRID_DIM
CELL_SIZE = 64
ICON_PADDING = 2
INNER_SIZE = CELL_SIZE - (ICON_PADDING * 2)
SHEET_PIXEL_DIM = GRID_DIM * CELL_SIZE
WEBP_QUALITY = 84

EXT_TO_CODE = {
    ".png": 0,
    ".gif": 1,
    ".webp": 2,
    ".jpg": 3,
    ".jpeg": 4,
}
CODE_TO_EXT = ["png", "gif", "webp", "jpg", "jpeg"]


@dataclass(frozen=True)
class IndexedEmoji:
    """Represents a normalized emoji entry ready for sprite packing and indexing."""

    idx: int
    name: str
    slug: str
    ext_code: int
    source_path: Path


def extract_preview_frame(image_path: Path) -> Image.Image:
    """Loads an image safely, falling back to truncated/corrupt stream recovery

    if standard decoding fails on malformed IDAT chunks.
    """
    canvas = Image.new("RGBA", (CELL_SIZE, CELL_SIZE), (0, 0, 0, 0))
    img = None
    try:
        # Enable Pillow's truncated file loading mode to salvage corrupt PNGs
        from PIL import ImageFile
        ImageFile.LOAD_TRUNCATED_IMAGES = True

        img = Image.open(image_path)
        img.load()
    except Exception as exc:
        print(f"[warn] Salvaging corrupt/truncated image '{image_path.name}': {exc}")
        # If even truncated loading fails, return the blank canvas
        return canvas

    try:
        valid_frame = None
        max_frames = getattr(img, "n_frames", 1)
        for frame_idx in range(min(max_frames, 10)):
            try:
                img.seek(frame_idx)
                if img.width > 0 and img.height > 0:
                    valid_frame = img.copy().convert("RGBA")
                    break
            except Exception:
                continue

        if valid_frame is None:
            valid_frame = img.convert("RGBA")

        thumb = ImageOps.contain(valid_frame, (INNER_SIZE, INNER_SIZE), method=Image.Resampling.LANCZOS)
        offset_x = ICON_PADDING + (INNER_SIZE - thumb.width) // 2
        offset_y = ICON_PADDING + (INNER_SIZE - thumb.height) // 2
        canvas.paste(thumb, (offset_x, offset_y), thumb)
    except Exception as exc:
        print(f"[warn] Failed to render preview for '{image_path.name}': {exc}")
    finally:
        if img:
            try:
                img.close()
            except Exception:
                pass

    return canvas


def build_single_sheet(sheet_idx: int, batch: list[IndexedEmoji], sprites_dir: Path) -> Path:
    """Composites up to 256 64x64 emoji thumbnails into a 1024x1024 WebP sprite sheet.

    Args:
        sheet_idx: Zero-based index of the sprite sheet.
        batch: Slice of IndexedEmoji items belonging to this sheet.
        sprites_dir: Output directory for sprite sheet files.

    Returns:
        The Path to the written WebP sprite sheet.
    """
    sheet_img = Image.new("RGBA", (SHEET_PIXEL_DIM, SHEET_PIXEL_DIM), (0, 0, 0, 0))

    for local_idx, item in enumerate(batch):
        col = local_idx % GRID_DIM
        row = local_idx // GRID_DIM
        cell_img = extract_preview_frame(item.source_path)
        sheet_img.paste(cell_img, (col * CELL_SIZE, row * CELL_SIZE))

    out_path = sprites_dir / f"sheet_{sheet_idx:03d}.webp"
    sheet_img.save(out_path, format="WEBP", quality=WEBP_QUALITY, method=4)
    return out_path


def load_manifest_entries(manifest_path: Path) -> list[IndexedEmoji]:
    """Reads emojis_manifest.json and produces a sorted list of IndexedEmoji objects.

    Args:
        manifest_path: Path to emojis_manifest.json generated by the renamer script.

    Returns:
        List of IndexedEmoji objects ordered deterministically by slug.
    """
    raw_records: list[dict[str, Any]] = json.loads(manifest_path.read_text(encoding="utf-8"))
    raw_records.sort(key=lambda r: r["slug"].lower())

    entries: list[IndexedEmoji] = []
    for raw in raw_records:
        src_path = Path(raw["path"])
        src_path = src_path.parent / "public" / src_path.name
        ext = src_path.suffix.lower()
        ext_code = EXT_TO_CODE.get(ext, 0)
        entries.append(
            IndexedEmoji(
                idx=len(entries),
                name=raw["name"],
                slug=raw["slug"],
                ext_code=ext_code,
                source_path=src_path,
            )
        )
    return entries


def export_compact_index(entries: list[IndexedEmoji], output_path: Path) -> None:
    """Writes a minified, zero-coordinate JSON index for the frontend virtual grid.

    Each item in the 'items' array is either [slug, ext_code] when slug == name,
    or [slug, ext_code, name] when disambiguated, keeping the payload tiny.

    Args:
        entries: List of IndexedEmoji items in exact sprite-packing order.
        output_path: Destination Path for gallery_index.json.
    """
    compact_items: list[list[Any]] = []
    for item in entries:
        if item.slug == item.name:
            compact_items.append([item.slug, item.ext_code])
        else:
            compact_items.append([item.slug, item.ext_code, item.name])

    payload = {
        "meta": {
            "total": len(entries),
            "gridDim": GRID_DIM,
            "cellSize": CELL_SIZE,
            "exts": CODE_TO_EXT,
        },
        "items": compact_items,
    }

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(
        json.dumps(payload, separators=(",", ":"), ensure_ascii=False),
        encoding="utf-8",
    )


def build_gallery_assets(
    manifest_path: Path = Path("emojis_manifest.json"),
    output_dir: Path = Path("dist"),
    max_workers: int = 8,
) -> None:
    """Generates all 1024x1024 WebP sprite sheets and the compact JSON index.

    Args:
        manifest_path: Path to the source emojis_manifest.json file.
        output_dir: Root output folder where 'sprites/' and 'gallery_index.json' will be created.
        max_workers: Thread pool concurrency for sprite sheet generation.
    """
    if not manifest_path.is_file():
        raise FileNotFoundError(f"Manifest not found at '{manifest_path}'")

    entries = load_manifest_entries(manifest_path)
    total_sheets = math.ceil(len(entries) / ITEMS_PER_SHEET)
    sprites_dir = output_dir / "sprites"
    sprites_dir.mkdir(parents=True, exist_ok=True)

    print(
        f"[build] Packing {len(entries)} emojis ({CELL_SIZE}x{CELL_SIZE}px) "
        f"into {total_sheets} sheets ({SHEET_PIXEL_DIM}x{SHEET_PIXEL_DIM}px each)..."
    )

    batches = [
        (sheet_idx, entries[sheet_idx * ITEMS_PER_SHEET : (sheet_idx + 1) * ITEMS_PER_SHEET])
        for sheet_idx in range(total_sheets)
    ]

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        futures = [
            pool.submit(build_single_sheet, sheet_idx, batch, sprites_dir)
            for sheet_idx, batch in batches
        ]
        for completed_idx, future in enumerate(futures, start=1):
            sheet_path = future.result()
            if completed_idx % 10 == 0 or completed_idx == total_sheets:
                print(f"[build] [{completed_idx}/{total_sheets}] Wrote '{sheet_path.name}'")

    index_path = output_dir / "gallery_index.json"
    export_compact_index(entries, index_path)
    size_kb = index_path.stat().st_size / 1024
    print(f"[build] Wrote compact index '{index_path}' ({size_kb:.1f} KB raw)")


if __name__ == "__main__":
    build_gallery_assets()
